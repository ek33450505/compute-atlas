/**
 * build-hero-points.mjs
 *
 * Builds the homepage hero globe's point set as a static, CDN-cacheable
 * artifact instead of serializing it into every homepage RSC payload.
 *
 * The hero globe is purely decorative (aria-hidden) and never mounts below
 * Tailwind's `sm` breakpoint, yet inlining ~1k `{lat, lon, status}` points
 * into the server-rendered payload cost every visitor — phones included —
 * ~98 KB brotli on `/`. Emitting the same array to public/data means the
 * markup carries none of it and the globe fetches it after mount, from the
 * CDN, only on the viewports that actually draw it.
 *
 * The roster is anonymous: no facility ids, so the public file cannot be joined
 * back to a facility page. Coordinates are rounded to COORD_PRECISION decimals
 * (2dp, ~1.1 km): the globe renders at zoom <= 5, where one pixel is roughly
 * 1.2 km, so the rounding stays under about one pixel. Points that collapse to
 * the same {lat, lon, status} are emitted once, which also hides co-located
 * counts; the globe is decorative, so nothing depends on the point count.
 *
 * Output (generated by `prebuild`, gitignored):
 *   public/data/hero-points.json   [{ lat, lon, status }, ...]
 *
 * Runs in `prebuild`/`predev` (after ensure-data-snapshot), as part of
 * `npm run build:mapdata` (including under --skip-nhd, since it does no
 * network I/O) and standalone via `npm run build:heropoints`.
 *
 * Usage: node scripts/build-hero-points.mjs
 */

import { writeFileSync, mkdirSync, readFileSync, realpathSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

const FACILITIES_PATH = resolve(repoRoot, 'data/facilities.json');
const OUT_PATH = resolve(repoRoot, 'public/data/hero-points.json');

/** ~1.1 km — about one pixel at the globe's zoom <= 5. */
export const COORD_PRECISION = 2;

/** Half away from zero, matching roundPoint in lib/facility-slim.ts. */
function round(value) {
  const factor = 10 ** COORD_PRECISION;
  return (Math.sign(value) * Math.round(Math.abs(value) * factor)) / factor;
}

/**
 * Reduce facilities to anonymous, rounded, de-duplicated `{ lat, lon, status }`
 * points. Facilities without finite coordinates are skipped.
 */
export function toHeroPoints(facilities) {
  const seen = new Set();
  const points = [];
  for (const facility of facilities) {
    const lat = facility?.location?.lat;
    const lon = facility?.location?.lon;
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
    const point = { lat: round(lat), lon: round(lon), status: facility.status };
    const key = `${point.lat}|${point.lon}|${point.status}`;
    if (seen.has(key)) continue;
    seen.add(key);
    points.push(point);
  }
  return points;
}

/**
 * Read data/facilities.json and write public/data/hero-points.json.
 *
 * Fails loudly (throws) when the source is missing, unreadable, or yields no
 * points — a silently-empty artifact would blank the hero with no error
 * anywhere in the build.
 *
 * @returns {{ count: number, bytes: number, outPath: string }}
 */
export function buildHeroPoints() {
  let raw;
  try {
    raw = readFileSync(FACILITIES_PATH, 'utf8');
  } catch (err) {
    throw new Error(
      `build-hero-points: cannot read ${FACILITIES_PATH}: ${err.message}`
    );
  }

  let facilities;
  try {
    facilities = JSON.parse(raw);
  } catch (err) {
    throw new Error(
      `build-hero-points: ${FACILITIES_PATH} is not valid JSON: ${err.message}`
    );
  }

  if (!Array.isArray(facilities)) {
    throw new Error(
      `build-hero-points: expected ${FACILITIES_PATH} to be an array, got ${typeof facilities}`
    );
  }

  const points = toHeroPoints(facilities);

  if (points.length === 0) {
    throw new Error(
      `build-hero-points: produced 0 points from ${FACILITIES_PATH} — refusing to write an empty artifact that would blank the hero globe`
    );
  }

  const json = JSON.stringify(points);
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, `${json}\n`);

  return {
    count: points.length,
    bytes: Buffer.byteLength(json) + 1,
    outPath: OUT_PATH,
  };
}

// Runnable directly: node scripts/build-hero-points.mjs
// Symlink/space-safe entrypoint check — see scripts/is-entrypoint.ts (plain node cannot import .ts).
function isEntrypoint() {
  try {
    return import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href;
  } catch {
    return false;
  }
}
if (isEntrypoint()) {
  try {
    const { count, bytes, outPath } = buildHeroPoints();
    console.log(
      `hero-points: wrote ${count} points (${bytes} bytes) -> ${outPath.replace(`${repoRoot}/`, '')}`
    );
  } catch (err) {
    // lint-no-raw-error-logs: allow -- file-only build step; imports no DB code, so the error cannot carry bound params
    console.error(err.message);
    process.exit(1);
  }
}
